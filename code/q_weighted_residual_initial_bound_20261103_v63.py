#!/usr/bin/env python3
"""A safe dimension upper bound from a bounded, possibly incomplete GB.

Only the monomial ideal generated by leading terms of known ideal elements is
measured.  It is never called the full initial ideal or the full Hilbert series.
"""
import argparse
import hashlib
import json
from pathlib import Path
import resource
import subprocess
import time

ROOT=Path(__file__).resolve().parents[1]


def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--partial-run',type=Path,required=True)
    parser.add_argument('--output',type=Path,required=True)
    parser.add_argument('--degree-limit',type=int,default=12)
    parser.add_argument('--timeout',type=int,default=150)
    args=parser.parse_args();args.output.mkdir(parents=True,exist_ok=False)
    started=time.monotonic();previous=json.loads((args.partial_run/'report.json').read_text())
    original=(args.partial_run/'compute.m2').read_text()
    header=original[:original.index('print "LOADED";')]
    script=args.output/'compute.m2';summary=(args.output/'summary.txt').resolve()
    tail='print "LOADED"; gbTrace=1; G=gb(I,DegreeLimit=>'+str(args.degree_limit)+');\n'
    tail+='print "PARTIAL_GB_FINISHED"; B=gens G; J=monomialIdeal leadTerm B;\n'
    tail+='f=openOut "'+str(summary)+'";\n'
    tail+='f << "PARTIAL_BASIS_SIZE " << numgens source B << endl;\n'
    tail+='f << "MONOMIAL_IDEAL_DIMENSION " << dim(R/J) << endl;\n'
    tail+='f << "LEADING_MONOMIALS " << toString flatten entries gens J << endl;\n'
    tail+='close f;\nexit 0;\n'
    script.write_text(header+tail)
    def limits():
        resource.setrlimit(resource.RLIMIT_AS,(6000000000,6000000000))
        resource.setrlimit(resource.RLIMIT_CPU,(args.timeout,args.timeout+1))
    status='completed'
    with (args.output/'m2.log').open('w') as stream:
        try:
            result=subprocess.run(['M2','--script',str(script)],stdout=stream,stderr=subprocess.STDOUT,
                                  timeout=args.timeout,preexec_fn=limits)
            if result.returncode:status=f'exit_{result.returncode}'
        except subprocess.TimeoutExpired:status='timeout'
    log=(args.output/'m2.log').read_text()
    summary_text=summary.read_text() if summary.exists() else ''
    completed=status=='completed' and 'MONOMIAL_IDEAL_DIMENSION ' in summary_text
    report=dict(id='Q_WEIGHTED_RESIDUAL_INITIAL_BOUND_20261103_V63',completed=completed,status=status,
                coefficient_field=previous['coefficient_field'],a_rational=previous['a_rational'],
                partial_residual_weight_cut=previous['weight_cut'],
                selected_polynomial_count=previous['selected_nonzero_polynomials'],
                gb_degree_limit=args.degree_limit,
                measured_ideal='J generated by leading monomials of returned partial GB elements',
                ideal_inclusions='J subset in(I_weight_cut) subset in(I_full)',
                full_model_dimension_is_at_most_measured_dimension=True,
                full_model_dimension_or_Hilbert_series_computed=False,
                characteristic_zero_dimension_claimed=False,
                wall_timeout_seconds=args.timeout,memory_limit_bytes=6000000000,
                input_sha256={str(p.resolve().relative_to(ROOT)):sha(p) for p in
                              [Path(__file__),args.partial_run/'compute.m2',args.partial_run/'report.json']},
                script_sha256=sha(script),seconds=time.monotonic()-started)
    if completed:
        for label,key in [('MONOMIAL_IDEAL_DIMENSION','full_model_dimension_upper_bound'),
                          ('PARTIAL_BASIS_SIZE','partial_basis_size')]:
            report[key]=int(next(line.split()[1] for line in summary_text.splitlines() if line.startswith(label+' ')))
        report['leading_monomials']=next(line[len('LEADING_MONOMIALS '):] for line in summary_text.splitlines() if line.startswith('LEADING_MONOMIALS '))
        report['summary_sha256']=sha(summary)
    (args.output/'report.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps({k:v for k,v in report.items() if k!='input_sha256'},indent=2))


if __name__=='__main__':main()
