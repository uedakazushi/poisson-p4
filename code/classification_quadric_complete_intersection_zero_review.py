#!/usr/bin/env python3
"""Independent full symbolic CI22 rank-zero source Pfaffian exclusion.

Only standard Fraction polynomial arithmetic is reused; no producer/CAS import.
The full350 Jacobi matrix is generated by differentiating q1*A+q2*B itself.
Every symbolic Pfaffian identity is then checked in every coordinate block.
"""
from pathlib import Path
from itertools import combinations,combinations_with_replacement
from fractions import Fraction as F
from functools import lru_cache
import hashlib,json,resource,time
import classification_projected_veronese_zero_review as r


def main():
    start=time.monotonic();resource.setrlimit(resource.RLIMIT_CPU,(85,86));resource.setrlimit(resource.RLIMIT_AS,(1024*1024**2,1024*1024**2))
    root=Path(__file__).resolve().parents[1]
    paths=[root/'reports'/('CLASSIFICATION_SMOOTH_CI22_ZERO_PARITY_'+kind+'_20261107.json') for kind in ['DIAGNOSTIC','SYMBOLIC']]
    diagnostic,saved=[json.loads(p.read_text()) for p in paths]
    assert saved['input_diagnostic_sha256']==hashlib.sha256(paths[0].read_bytes()).hexdigest()
    assert hashlib.sha256(saved['producer_bytes'].encode()).hexdigest()==saved['producer_sha256']
    LL=['l'+str(i) for i in range(5)];ZZ=['a'+str(i) for i in range(10)]+['b'+str(i) for i in range(10)];XX=['x'+str(i) for i in range(5)]
    L=r.Ring(LL);Z=r.Ring(ZZ);U=r.Ring(LL+ZZ+XX)
    zero=F(0);unit=(0,)*5;pair_quads=list(combinations_with_replacement(range(20),2));pindex={q:i for i,q in enumerate(pair_quads)}
    assert [list(v) for v in pair_quads]==diagnostic['parameter_quadratic_monomial_indices']
    q1=r.plus(*(U.power(U.var(x),2) for x in XX));q2=r.plus(*(r.times(U.var(l),U.power(U.var(x),2)) for l,x in zip(LL,XX)))
    P={}
    for j,(a,b) in enumerate(r.PAIRS):P[a,b]=r.plus(r.times(q1,U.var('a'+str(j))),r.times(q2,U.var('b'+str(j))));P[b,a]=r.scale(P[a,b],-1)
    strict={tri:r.plus(*(r.times(P.get((a,l),{}),r.derivative(P.get((b,c),{}),25+l)) for a,b,c in [tri,(tri[1],tri[2],tri[0]),(tri[2],tri[0],tri[1])] for l in range(5))) for tri in r.TRIPLES}
    jac={quad:r.plus(*(r.scale(r.times(U.var('x'+str(quad[k])),strict[quad[:k]+quad[k+1:]]),(-1)**k) for k in range(4))) for quad in r.QUADS}
    labels=[(quad,e) for quad in r.QUADS for e in r.monomials(5,4)];row_index={v:i for i,v in enumerate(labels)};M=[{} for row in labels]
    for quad,poly in jac.items():
        for e,c in poly.items():
            indexes=[i for i,power in enumerate(e[5:25]) for k in range(power)];assert len(indexes)==2
            row=row_index[quad,e[25:]];col=pindex[tuple(indexes)];M[row][col]=r.plus(M[row].get(col,{}),{e[:5]:c})
    def evaluate(poly):return sum(c*math_product(F(i)**a for i,a in enumerate(e)) for e,c in poly.items())
    def math_product(values):
        out=F(1)
        for v in values:out*=v
        return out
    actual={str(i):{str(j):str(v) for j,p in row.items() if (v:=evaluate(p))} for i,row in enumerate(M) if any(evaluate(p) for p in row.values())}
    assert actual==diagnostic['full350_by210_sparse_Jacobi_matrix']
    assert labels==[(tuple(p['quad']),tuple(p['exponents'])) for p in diagnostic['rows']]
    rows=saved['selected_original350_rows'];cols=saved['parameter_monomial_columns'];pc=saved['selected_pivot_columns']
    assert [[M[i].get(j,{}) for j in cols] for i in rows]==[[L.parse(v) for v in row] for row in saved['symbolic_six_by_twelve_matrix']]
    # Exact symbolic maximal minor by sparse Laplace expansion, no CAS.
    @lru_cache(None)
    def det_sub(rr,cc):
        if not rr:return L.const(1)
        chosen=min(range(len(rr)),key=lambda k:sum(bool(M[rr[k]].get(j)) for j in cc));i=rr[chosen];out={}
        for pos,j in enumerate(cc):
            p=M[i].get(j,{})
            if p:out=r.plus(out,r.scale(r.times(p,det_sub(rr[:chosen]+rr[chosen+1:],cc[:pos]+cc[pos+1:])),(-1)**(chosen+pos)))
        return out
    determinant=det_sub(tuple(rows),tuple(pc));assert determinant==L.parse(saved['selected_rank_minor'])
    assert determinant==L.parse('-64*(l0-l1)**3*(l0-l2)*(l0-l3)*(l0-l4)')
    # Independently reconstruct every actual denominator as a Vandermonde unit.
    denominators=[]
    for p in saved['all_functional_denominators']:
        assert not p['unhandled_factors'];v=L.const(F(p['rational_unit']))
        for factor in p['difference_factors']:
            base=r.scale(r.plus(L.var('l'+str(factor['i'])),r.scale(L.var('l'+str(factor['j'])),-1)),F(factor['rational_unit']))
            v=r.times(v,L.power(base,factor['power']))
        assert v==L.parse(p['denominator']);denominators.append(v)
    def exact_quotient(numerator,denominator):
        assert denominator;out={};left=dict(numerator);lead=max(denominator)
        while left:
            e=max(left);assert all(a>=b for a,b in zip(e,lead))
            term={tuple(a-b for a,b in zip(e,lead)):left[e]/denominator[lead]};out=r.plus(out,term);left=r.plus(left,r.scale(r.times(term,denominator),-1))
        return out
    cleared=[]
    for function in saved['three_exact_full350_Jacobi_functional_fractions']:
        row={}
        for i,value in function.items():
            num,den=L.parse(value['numerator']),L.parse(value['denominator']);assert den in denominators
            row[int(i)]=r.times(num,exact_quotient(determinant,den))
        cleared.append(row)
    def matrix_variables(offset):
        P={}
        for j,ij in enumerate(r.PAIRS):P[ij]=Z.var(ZZ[offset+j]);P[ij[::-1]]=r.scale(P[ij],-1)
        return P
    AA,BB=matrix_variables(0),matrix_variables(10)
    def pf(P,quad):
        a,b,c,d=quad
        return r.plus(r.times(P[a,b],P[c,d]),r.scale(r.times(P[a,c],P[b,d]),-1),r.times(P[a,d],P[b,c]))
    AB={ij:r.plus(AA[ij],BB[ij]) for ij in AA}
    def target_rows(quad):
        a,b=pf(AA,quad),pf(BB,quad);mixed=r.plus(pf(AB,quad),r.scale(a,-1),r.scale(b,-1));out=[]
        for poly in [a,mixed,b]:
            row={}
            for e,c in poly.items():
                index=tuple(i for i,power in enumerate(e) for k in range(power));assert len(index)==2;row[pindex[index]]=c
            out.append(row)
        return out
    def permute_poly(poly,perm):
        out={}
        for e,c in poly.items():
            f=[0]*5
            for i,power in enumerate(e):f[perm[i]]=power
            out[tuple(f)]=c
        return out
    checks=[]
    for quad in r.QUADS:
        missing=next(i for i in range(5) if i not in quad);perm=tuple(quad)+(missing,);targets=target_rows(quad);D=permute_poly(determinant,perm);functions=[]
        for original in cleared:
            function={}
            for row,weight in original.items():
                old_quad,old_exp=labels[row];new_quad=[perm[i] for i in old_quad];sign=(-1)**sum(new_quad[i]>new_quad[j] for i in range(4) for j in range(i+1,4));new_exp=[0]*5
                for i,power in enumerate(old_exp):new_exp[perm[i]]=power
                new_row=row_index[tuple(sorted(new_quad)),tuple(new_exp)];function[new_row]=r.scale(permute_poly(weight,perm),sign)
            functions.append(function)
        block=[j for j,(a,b) in enumerate(pair_quads) if set(r.PAIRS[a%10])^set(r.PAIRS[b%10])==set(quad)];assert len(block)==12
        assert all(set(M[row])<=set(block) for function in functions for row in function)
        for target,function in zip(targets,functions):
            for col in block:
                actual=r.plus(*(r.times(weight,M[row].get(col,{})) for row,weight in function.items()))
                assert actual==r.scale(D,target.get(col,zero))
        # Check that all rows in this block really are among the full350 rows.
        point_rows=[[evaluate(M[i].get(j,{})) for j in block] for i in range(350) if any(j in M[i] for j in block)]
        assert len(r.sparse_rref(point_rows)[0])==6
        checks.append({'quad':list(quad),'coordinate_permutation':list(perm),'all_three_symbolic_Pfaffian_identities_from_full350_passed':True,
            'denominator_cleared_common_minor':[[list(e),str(c)] for e,c in sorted(D.items())],
            'no_nonVandermonde_exception':True,'full12_column_block_diagnostic_rank':6})
        print('ALL SYMBOLIC CI22 BLOCK PASS',quad,flush=True)
    out={'task_id':'G','all_passed':True,'no_producer_or_CAS_import':True,'complete20_parameter_source_retained':True,
        'full350_by210_universal_Jacobi_matrix_reconstructed_from_actual_Pi':True,'entire_rational_diagnostic_exactly_reconstructed':True,
        'full_symbolic_six_by_twelve_matrix_and_rank_minor_reconstructed':True,'only_Vandermonde_differences_inverted':True,
        'all_five_blocks':checks,'all_PfA_PfAB_PfB_in_full_Jacobi_ideal_on_all_distinct_eigenvalues':True,
        'every_smooth_CI22_rankzero_Poisson_source_has_rank_at_most2':True,
        'input_sha256':{str(p.relative_to(root)):hashlib.sha256(p.read_bytes()).hexdigest() for p in paths+[Path(r.__file__)]},
        'reviewer_sha256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),'reviewer_source_bytes':Path(__file__).read_text(),
        'seconds':time.monotonic()-start,'maximum_RSS_KiB':resource.getrusage(resource.RUSAGE_SELF).ru_maxrss,
        'scope':'Independent actual-bracket differentiation of full350 symbolic equations, denominator-cleared identities in all five parity blocks with real permutation signs, and every Vandermonde factor. Koszul/Bott source completeness and smooth-pencil diagonal normal form remain separately proved geometric inputs. Nonzero rank2 sources retained; singular CI and rank2-on-S cases are separate.'}
    dest=root/'reports/CLASSIFICATION_SMOOTH_CI22_ZERO_PARITY_REVIEW_20261107.json'
    if dest.exists():raise FileExistsError(dest)
    dest.write_text(json.dumps(out,indent=2)+'\n');print(json.dumps({'all_passed':True,'seconds':out['seconds'],'maximum_RSS_KiB':out['maximum_RSS_KiB']}))

if __name__=='__main__':main()
