#!/usr/bin/env python3
"""Audit residue-field recovery of a point of the generic elliptic quintic at infinity."""
import argparse
import hashlib
from itertools import combinations
import json
from pathlib import Path
import time

import sympy as sp

from primitive_jet_elliptic_curve_20261101 import primitive_beta
from s61_model import S61
from weight1_structure import J

ROOT=Path(__file__).resolve().parents[1]
STEM='S61_GENERIC_BOUNDARY_INDEX_20261102'


def common_factor_space(q, variables):
    vectors=sp.symbols('t:4')
    rows=[]
    for i,j,k in combinations(range(4),3):
        coefficient=vectors[i]*q[j,k]-vectors[j]*q[i,k]+vectors[k]*q[i,j]
        rows.extend(sp.Poly(coefficient,*variables).coeffs())
    matrix=sp.Matrix(rows).jacobian(vectors)
    return sp.Matrix.hstack(*matrix.nullspace())


def verify():
    start=time.monotonic()
    y,u,beta=primitive_beta(S61())
    T=[beta.diff(x) for x in y]
    e=sp.eye(4)
    v,w=e[:,1],e[:,3]
    # The surviving flag directions use the same vertex in both incidence tests.
    flag_section=[sp.expand((v.T*T[i]*w)[0]) for i in (1,3)]
    uv={str(x):x for x in u}
    assert flag_section==[uv['u4'],uv['u5']]
    tau=v.T*T[1]
    omega=v.T*J
    assert omega==sp.Matrix([[-1,0,0,0]])
    assert tau==sp.Matrix([[3*uv['u49']/5,0,-uv['u12'],uv['u4']]])
    assert sp.Matrix(flag_section).jacobian(u).rank()==2
    # Build the ordinary big cell of LG(2,4) as lower unipotent symplectic graphs.
    a,b,c=sp.symbols('a b c')
    perm=[0,2,1,3]
    shear=sp.eye(4)
    shear[2:4,0:2]=sp.Matrix([[a,b],[b,c]])
    invperm=[perm.index(i) for i in range(4)]
    shear=shear.extract(invperm,invperm)
    assert shear.T*J*shear==J and shear.det()==1
    # Test coefficient-linear reconstruction of the two constant-factor cases.
    x,_,z,wvar=y
    split=sp.zeros(4)
    split[1,2]=x*wvar
    split-=split.T
    nonsplit=split*(x*x+2*x*wvar+3*wvar*wvar)/(x*wvar)
    nonsplit=nonsplit.applyfunc(sp.cancel)
    assert common_factor_space(nonsplit,y)==e[:,[1,2]]
    nonbinary=sp.zeros(4)
    nonbinary[1,2]=x*z
    nonbinary[1,3]=-x*wvar
    nonbinary-=nonbinary.T
    assert common_factor_space(nonbinary,y)==v
    flag=sp.zeros(4)
    flag[1,3]=-x*x
    flag-=flag.T
    assert common_factor_space(flag,y)==e[:,[1,3]]
    quadratic_matrix=sp.hessian(-x*x,y)
    square_line=sp.Matrix.hstack(*quadratic_matrix.columnspace())
    assert square_line.rank()==1
    assert (J*square_line).row_join(v).rank()==1
    minimal=sp.zeros(4)
    minimal[0,1]=x*x
    minimal-=minimal.T
    divergence=sp.Matrix([sum(minimal[i,j].diff(y[i]) for i in range(4)) for j in range(4)])
    modular=divergence.jacobian(y)
    assert modular.rank()==1 and modular.row_join(v).rank()==1 and modular**2==sp.zeros(4)
    sources=['PRIMITIVE_JET_ELLIPTIC_CURVE_20261101','PRIMITIVE_CURVE_DISCRIMINANT_20261101',
             'NULL_CORRELATION_DUALITY_20261101','S61_AFFINE_BOUNDARY_DIMENSION_20261102',
             'S61_R0_INFINITY_20261101','S61_R0_GENERIC_EXHAUSTION_20261101',
             'S61_MINIMAL_INFINITY_VERTEX_NECESSITY_20261101','S61_FLAG_UNIFORM_OPEN_20261101',
             'S61_AFFINE_SURFACE_BOUND_20261102']
    files=[Path(__file__),ROOT/'research/notes'/(STEM+'.md'),
           ROOT/'research/notes/S61_GENERIC_REDUCED_INFINITY_EXHAUSTION_20261101.md']
    for name in sources:
        report=ROOT/'reports'/(name+'.json')
        assert json.loads(report.read_text())['all_passed']
        files.extend([report,ROOT/'research/notes'/(name+'.md')])
    files.extend(ROOT/'code'/n for n in ['primitive_jet_elliptic_curve_20261101.py','s61_model.py',
                                        's61_infinity_flags.py','elliptic_weight1_dominance.py',
                                        'weight1_structure.py'])
    files.extend(ROOT/'legacy/v02/data'/n for n in ['symplectic_slice_certificate.json',
                'symplectic_slice_equations.json','symplectic_slice_reduced_equations.json'])
    return dict(id=STEM,all_passed=True,algebraic_ground_field='K=C(W16)',
                flag_support_section=list(map(str,flag_section)),vertex_covector=list(map(str,tau)),
                symplectic_vertex_covector=list(map(str,omega)),fixed_plane_section_evaluation_rank=2,
                proper_universal_curve_incidence_vector_bundle_rank=14,canonical_curve_degree=5,
                actual_picard_group_of_generic_curve='Z generated by O_C(1)',generic_curve_index=5,
                dual_to_curve_picard_map='L -> L^2 tensor O_C(-1), from Pic^3 to Pic^1=C',
                factor_kernel_dimensions_in_coordinate_examples={'binary':2,'nonbinary':1,'flag':2},
                minimal_modular_example_rank=1,all_true_boundary_closed_point_degrees_divisible_by=5,
                positive_dimensional_K_projective_closure_degrees_divisible_by=5,
                assumptions='Use the audited generic leading-equation type cover and true-boundary flag removal.',
                input_sha256={str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest()
                              for p in files},seconds=time.monotonic()-start)


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,required=True)
    args=parser.parse_args()
    report=verify()
    with args.output.open('x') as stream:
        json.dump(report,stream,indent=2)
        stream.write('\n')
    print('PASS',round(report['seconds'],3))
