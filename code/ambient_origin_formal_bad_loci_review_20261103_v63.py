#!/usr/bin/env python3
"""Independent monomial/support, local-AB and transverse-count bad-loci review."""
import argparse,hashlib,json,subprocess,tempfile,time
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def divides(a,b):return all(i<=j for i,j in zip(a,b))
def reduced(gens):return sorted({g for g in gens if not any(h!=g and divides(h,g)for h in gens)})
def same_ideal(a,b):return all(any(divides(h,g)for h in b)for g in a)and all(any(divides(h,g)for h in a)for g in b)
def main(out):
    started=time.monotonic();out.mkdir(parents=True,exist_ok=False)
    source=ROOT/'code/ambient_origin_formal_bad_loci_20261103_v63.py';author=ROOT/'reports/AMBIENT_ORIGIN_FORMAL_BAD_LOCI_20261103_v63.json';d=json.loads(author.read_text());assert d['all_passed'] is True
    for name,digest in d['input_sha256'].items():assert sha(ROOT/name)==digest,name
    with tempfile.TemporaryDirectory(prefix='bad-loci-review-')as tmp:
        receipt=Path(tmp)/'replay.json';run=subprocess.run([str(ROOT/'.venv/bin/python'),str(source),'--output',str(receipt)],capture_output=True,text=True,check=True,timeout=30)
        assert receipt.read_bytes()==author.read_bytes()
    K=[(1,1,0),(1,0,1),(0,2,1)]
    # Colon by one monomial is generated by g/gcd(g,m), proved by
    # divisibility of each original generator; no sampled monomial cutoff.
    def own_colon(variable):
        m=tuple(int(i==variable)for i in range(3))
        return reduced([tuple(a-min(a,b)for a,b in zip(g,m))for g in K])
    cw=own_colon(0);cr=own_colon(1)
    assert same_ideal(cw,[(0,1,0),(0,0,1)])
    assert same_ideal(cr,[(1,0,0),(0,1,1)])
    meet=reduced([tuple(max(a,b)for a,b in zip(g,h))for g in cw for h in cr])
    radical=reduced([tuple(int(a>0)for a in g)for g in K])
    assert same_ideal(meet,[(1,1,0),(1,0,1),(0,1,1)])and same_ideal(meet,radical)
    assert same_ideal([*K,(0,1,1)],meet)
    # Independent local formulas: edim=dimR+mu(ideal) for proper
    # conductors; depth=min(dimR,depth(R/ideal)+1). Off conductor B regular.
    original={};seminormal={}
    for name,dim,mu,depthC in [('W_V',9,9,0),('S',9,9,0),('G',10,10,1)]:
        original[name]=[dim,dim+mu,min(dim,depthC+1)]
    for name,dim,mu,depthC in [('S',9,9,0),('G',10,9,1)]:
        seminormal[name]=[dim,dim+mu,min(dim,depthC+1)]
    seminormal['W_V']=[9,9,9]
    assert original==d['generic_transverse_dim_edim_depth_original']
    assert seminormal==d['generic_transverse_dim_edim_depth_seminormal']
    center=[i+19 for i in original['G']];center_sn=[i+19 for i in seminormal['G']]
    assert center+[2]==d['central_cone_dim_edim_depth_multiplicity_original']
    assert center_sn+[2]==d['central_cone_dim_edim_depth_multiplicity_seminormal']
    assert [i-1 for i in center]+[2]==d['projective_original']
    assert [i-1 for i in center_sn]+[2]==d['projective_seminormal']
    evidence=dict(ambient_monomial_ideal=K,own_colon_w=cw,own_colon_r=cr,own_intersection=meet,own_radical=radical,
      all_colon_equalities_by_divisibility_not_bounded_sampling=True,
      local_regular_base_heights={'W':9,'V':9,'S':9,'G':10},
      original_transverse=original,seminormal_transverse=seminormal,
      whole_cone_original=center+[2],whole_cone_seminormal=center_sn+[2],
      exact_author_replay_stdout=run.stdout.strip())
    (out/'independent-evidence.json').write_text(json.dumps(evidence,indent=2)+'\n')
    note=ROOT/'research/notes/AMBIENT_ORIGIN_FORMAL_BAD_LOCI_20261103_v63_REVIEW.md'
    paths=[Path(__file__),note,source,author,*[ROOT/'reports'/name/'report.json'for name in['AMBIENT_ORIGIN_FULL_FORMAL_MODEL_20261103_v63_REVIEW','AMBIENT_ORIGIN_SEMINORMALIZATION_20261103_v63_REVIEW']]]
    result=dict(id='AMBIENT_ORIGIN_FORMAL_BAD_LOCI_20261103_v63_REVIEW',all_passed=True,
      fresh_author_receipt_byte_identical=True,
      independent_exact_monomial_colons_intersection_and_nilradical_checked=True,
      intrinsic_conductor_support_and_nonseminormal_module_support_equalities_proved=True,
      all_conductor_prime_local_AB_argument_and_height9_checked=True,
      fiber_in_local_AB_proof_interpreted_as_A_tensor_kappa_p_not_unlocalized_A_mod_p=True,
      unique_prime_of_A_over_each_conductor_prime_of_R_verified=True,
      all_normalization_fibers_checked_from_kappa_t_quadratic_and_unit_strata=True,
      independent_generic_transverse_and_full_cone_projective_dimensions_depths_edims_match=True,
      generic_transverse_numbers_not_decreased_again_for_projectivization=True,
      multiplicity2_by_integral_reduction_and_rank2_checked=True,
      exact_original_reduced_bad_loci='Sing=Nonnormal=NonCM=Nonseminormal=whole W union V union S',
      exact_seminormal_reduced_bad_loci='Sing=Nonnormal=NonCM=S;Nonseminormal empty',
      scope='Each individual formal completion only; no global, convergent, or relative CA/CB statement.',
      input_sha256={str(p.relative_to(ROOT)):sha(p)for p in paths},evidence_sha256={'independent-evidence.json':sha(out/'independent-evidence.json')},seconds=time.monotonic()-started)
    (out/'report.json').write_text(json.dumps(result,indent=2)+'\n');print('INDEPENDENT FORMAL BAD LOCI /LOCAL AB /COLONS /ALL STRATA PASS',result['seconds'],flush=True)
if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--output',type=Path,required=True);main(ap.parse_args().output.resolve())
