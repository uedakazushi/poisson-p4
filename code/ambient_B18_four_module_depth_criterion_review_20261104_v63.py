def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


def read(p):
    return json.loads(p.read_text())


def add(u, v):
    return [a + b for a, b in zip(u, v)]


def scale(a, u):
    return [a * x for x in u]


class Space:
    """Own Fraction row-echelon engine, used only in <=12-dimensional toys."""
    def __init__(self, vectors=()):
        self.rows = {}
        for v in vectors:
            r = self.reduce(v)
            p = next((i for i, x in enumerate(r) if x), None)
            if p is not None:
                self.rows[p] = scale(1 / r[p], r)

    def reduce(self, v):
        r = list(map(F, v))
        for p, b in sorted(self.rows.items()):
            r = add(r, scale(-r[p], b))
        return r

    def contains(self, v):
        return not any(self.reduce(v))

    def vectors(self):
        return list(self.rows.values())


def equal(u, v):
    return (all(v.contains(x) for x in u.vectors())
            and all(u.contains(x) for x in v.vectors()))


def nullspace(columns, nrows):
    n = len(columns)
    a = [[F(columns[j][i]) for j in range(n)] for i in range(nrows)]
    pivots, r = [], 0
    for c in range(n):
        k = next((k for k in range(r, nrows) if a[k][c]), None)
        if k is None:
            continue
        a[r], a[k] = a[k], a[r]
        a[r] = scale(1 / a[r][c], a[r])
        for k in range(nrows):
            if k != r and a[k][c]:
                a[k] = add(a[k], scale(-a[k][c], a[r]))
        pivots.append(c)
        r += 1
    out = []
    for c in set(range(n)) - set(pivots):
        z = [F(0)] * n
        z[c] = F(1)
        for k, p in enumerate(pivots):
            z[p] = -a[k][c]
        out.append(z)
    return out


def intersect(u, v, dim):
    ub = u.vectors()
    relations = nullspace([v.reduce(x) for x in ub], dim)
    ans = []
    for z in relations:
        x = [F(0)] * dim
        for c, b in zip(z, ub):
            x = add(x, scale(c, b))
        ans.append(x)
    return Space(ans)


def finite_toy(N, i0, j0, descriptions):
    # R0=k[x]/x^N, tau^2=x. Use tau exponents modulo tau^(2N).
    # Directly multiply the finite algebra, rather than run the author's schema.
    dim = 2 * N
    def poly(terms):
        v = [F(0)] * dim
        for e, c in terms.items():
            if e < dim:
                v[e] += F(c)
        return v
    def mul(u, v):
        z = [F(0)] * dim
        for i, a in enumerate(u):
            for j, b in enumerate(v[:dim-i]):
                z[i+j] += a*b
        return z
    c = Space([poly({e: 1}) for e in range(dim)
               if e % 2 == 0 or e >= 2*i0+1])
    h = Space([poly({e: 1}) for e in range(dim)
               if e % 2 == 0 or e >= 2*min(i0, j0)+1])
    qs = [(d, poly(terms)) for d, terms in descriptions]
    assert all((c if d == 0 else h).contains(v) for d, v in qs)
    # Multiplication closure of the actual A coefficient spaces.
    assert all(c.contains(mul(u, v)) for u in c.vectors() for v in c.vectors())
    assert all(h.contains(mul(u, v)) for u in h.vectors() for v in h.vectors())
    qn = []
    for n in range(9):
        generators = []
        for d, q in qs:
            if d <= n:
                multiplier = c if d == n else h
                generators += [mul(q, v) for v in multiplier.vectors()]
        qn.append(Space(generators))
    stable = Space([mul(q, v) for d, q in qs for v in h.vectors()])
    assert all(equal(qn[n], stable) for n in range(4, 9))
    dims = []
    for n in range(5):
        a = c if n == 0 else h
        # Kernel of w^4 into the actual degree n+4 quotient.
        ker4 = intersect(a, qn[n+4], dim)
        expected = intersect(a, stable, dim)
        assert equal(ker4, expected)
        assert all(ker4.contains(v) for v in qn[n].vectors())
        dims.append(len(ker4.rows) - len(qn[n].rows))
    assert dims[4] == 0
    # H/C0 is R0-generated by j*tau; multiply cubic inputs and all x-powers.
    top = qn[3].vectors()
    for d, q in qs:
        if d == 3:
            target = mul(poly({2*j0+1: 1}), q)
            top += [mul(poly({2*k: 1}), target) for k in range(N)]
    assert equal(Space(top), stable)
    return {'N': N, 'I0_x_power': i0, 'J0_x_power': j0,
            'generator_weights': [d for d, _ in qs],
            'torsion_coefficient_dimensions_0to4': dims,
            'direct_finite_algebra_kernel_and_top_generator_checks': True}


